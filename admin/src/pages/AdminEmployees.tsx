const resolveDeptSelection = (dept: string | null | undefined): { selectValue: string; customValue: string } => {
  if (!dept || !dept.trim()) {
    return { selectValue: '', customValue: '' };
  }
  const trimmed = dept.trim();
  const matched = STANDARD_DEPARTMENTS.find(
    (d) => d.toLowerCase() === trimmed.toLowerCase()
  );
  if (matched) {
    return { selectValue: matched, customValue: '' };
  }
  return { selectValue: 'Other', customValue: trimmed };
};

